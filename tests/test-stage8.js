    assert.strictEqual(decTied.action, 'needs_user');
    assert(decTied.reason.includes('tie between options 1 and 2'), `Reason must explain tie between options 1 and 2, got: ${decTied.reason}`);

    // 5.8: endsWith continues to work on normalized text
    const endsWithRule = {
      name: 'ends-rule',
      startsWith: 'Yes',
      endsWith: 'in this conversation',
      enabled: true
    };
