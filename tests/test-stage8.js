    const mockPty = {
      write: (data) => forwardedChunks.push(Buffer.isBuffer(data) ? data.toString('utf8') : String(data)),
      onData: () => {},
      onExit: () => {}
    };
    const mockStdin = new EventEmitter();
    mockStdin.isTTY = true;
    mockStdin.setRawMode = () => {};

