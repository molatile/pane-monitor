    assert(!matchesOptionRule(endsWithRule, tieBreakWithPersistPrompt.options[2], tieBreakWithPersistPrompt), 'endsWith must reject Option 3');

    // 5.9: "No" options are NEVER candidates
    const noRule = {
      name: 'no-rule',
      startsWith: 'No',
      enabled: true
    };
    assert.strictEqual(matchesOptionRule(noRule, tieBreakWithPersistPrompt.options[3], tieBreakWithPersistPrompt), false, '"No" options are NEVER candidates');

    suitePassCounts['Suite 5: Item E - Best-Match Option Rules'] += 9;
    console.log('  ✓ Normalization, candidate startsWith, least extra text, tie explanation, endsWith, and guards verified');
