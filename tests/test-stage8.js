    fs.writeFileSync(guiHeartbeatFile, JSON.stringify({ pid: 12345, type: 'gui', time: staleTime }), 'utf8');
    // Set mtime to past as well
    const pastDate = new Date(staleTime);
    fs.utimesSync(guiHeartbeatFile, pastDate, pastDate);
    assert.strictEqual(hasFreshViewer(viewersDir, 10000), false, 'Heartbeat older than 10s must be treated as stale');

    // 2.3: Wrapper pauses auto-accept when no fresh viewer for 10s
    let outputLines = [];
