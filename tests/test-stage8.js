    fs.writeFileSync(guiHeartbeatFile, JSON.stringify({ pid: 12345, type: 'gui', time: Date.now() }), 'utf8');
    const freshDate = new Date();
    fs.utimesSync(guiHeartbeatFile, freshDate, freshDate);
    agentwatchInstance.checkViewerPause();
    assert.strictEqual(agentwatchInstance.isViewerPaused(), false, 'Auto-accept must resume automatically when viewer is back');

    // 2.5: Setting "Keep accepting when no window is open" (keepAcceptingWhenNoWindow: true)
    fs.unlinkSync(guiHeartbeatFile); // remove viewer again
    const cfg = loadConfig(configPath);
    assert.strictEqual(cfg.keepAcceptingWhenNoWindow, false, 'Default keepAcceptingWhenNoWindow must be false');
    setKeepAcceptingWhenNoWindow(cfg, true, configPath);
    assert.strictEqual(loadConfig(configPath).keepAcceptingWhenNoWindow, true);

    agentwatchInstance.checkViewerPause();
    assert.strictEqual(agentwatchInstance.isViewerPaused(), false, 'Auto-accept must NOT pause when keepAcceptingWhenNoWindow is enabled');

